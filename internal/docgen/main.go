// Command docgen writes docs/rules.md from the rule catalog, so the
// reference cannot drift from the code. Run it with `go generate ./...`.
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"strings"

	"github.com/xceg/sphinx"
)

func render() []byte {
	var b bytes.Buffer
	b.WriteString("<!-- Generated by internal/docgen from the rule catalog. Do not edit. -->\n\n")
	b.WriteString("# Rules\n\n")
	b.WriteString("Every finding Sphinx reports belongs to one of these rules. `sphinx rules RULE` prints the same text in the terminal.\n\n")
	b.WriteString("| ID | Name | Severity | Formats | Reveal | Seal |\n|---|---|---|---|:-:|:-:|\n")
	for _, r := range sphinx.Rules() {
		fmt.Fprintf(&b, "| [%s](#%s) | `%s` | %s | %s | %s | %s |\n", r.ID, strings.ToLower(r.ID), r.Name, r.Severity, strings.Join(r.Formats, ", "), mark(r.Reveal), mark(r.Seal))
	}
	b.WriteString("\nSeverity is the default; a finding can be raised or lowered by context (text under a coloured shape is `high`, under a black one `critical`). \"Seal\" means `sphinx seal` removes the leak.\n")
	for _, r := range sphinx.Rules() {
		fmt.Fprintf(&b, "\n## %s\n\n**%s** · `%s` · %s\n\n%s\n\n**What to do.** %s\n", r.ID, r.Title, r.Name, r.Severity, r.Why, r.Fix)
	}
	return b.Bytes()
}

func mark(ok bool) string {
	if ok {
		return "yes"
	}
	return ""
}

func main() {
	out := flag.String("o", "docs/rules.md", "output file")
	flag.Parse()
	if err := os.WriteFile(*out, render(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
